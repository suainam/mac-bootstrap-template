def _truncate_head_tail(text: str, limit: int) -> str:
    """Keep the head and the tail, drop the middle, never exceed ``limit``.

    The head carries the summary and the stat header; the tail carries the last
    hunks and the final log line. The middle is the part a model would only use
    to burn tokens.
    """
    if not text:
        return ""
    if len(text) <= limit:
        return text
    budget = max(0, limit - len(TRUNCATION_MARKER))
    head = budget // 2
    tail = budget - head
    if tail <= 0:
        return text[:limit]
    return text[:head] + TRUNCATION_MARKER + text[-tail:]


def truncate_handoff(text: str, limit: int = MAX_HANDOFF_CHARS) -> str:
    """Bound the worker's own narration."""
    return _truncate_head_tail(text or "", limit)


def truncate_test_output(text: str, limit: int = MAX_TEST_OUTPUT_CHARS) -> str:
    """Keep the tail of a test log: the pass/fail summary is at the end."""
    if not text:
        return ""
    if len(text) <= limit:
        return text.rstrip()
    return TRUNCATION_MARKER + text[-max(0, limit - len(TRUNCATION_MARKER)):].rstrip()


def truncate_diff(text: str, limit: int = MAX_DIFF_SUMMARY_CHARS) -> str:
    """Bound a diff summary to its stat header and final hunks."""
    return _truncate_head_tail(text or "", limit)


