def _diff_signals(diff_text: str) -> Tuple[list, list]:
    """Find degradation and uncorroborated-claim signals in the evidence."""
    degradation: list = []
    for line in diff_text.splitlines():
        if _REMOVED_ASSERTION_RE.match(line) or _COMMENTED_ASSERTION_RE.match(line):
            degradation.append(f"assertion removed or commented out: {line.strip()[:120]}")
        elif _SKIPPED_TEST_RE.match(line):
            degradation.append(f"test skipped or muted: {line.strip()[:120]}")
        elif _REMOVED_VALIDATION_RE.match(line):
            degradation.append(f"validation removed: {line.strip()[:120]}")

    return degradation, []


def _uncorroborated_claims(handoff_text: str, evidence: str) -> list:
    """Named verification tools the handoff claims but the evidence never shows.

    The claim must sit in a verification context, otherwise an ordinary sentence
    like "added regression coverage" would be read as a coverage-tool claim.
    """
    haystack = handoff_text or ""
    claimed: list = []
    for label, pattern in _VERIFICATION_TOOL_PATTERNS.items():
        tool = re.compile(pattern, re.IGNORECASE)
        for match in tool.finditer(haystack):
            window_start = max(0, match.start() - 60)
            window = haystack[window_start:match.end() + 40]
            if not _VERIFICATION_CONTEXT_RE.search(window):
                continue
            if re.search(pattern, evidence, re.IGNORECASE):
                break  # corroborated; stop looking at this tool
            claimed.append(label)
            break
    return claimed


def _heuristic_verdict(
    handoff_text: str,
    test_output: str,
    diff_summary: str,
    p_unverified: float = 0.0,
    p_degradation: float = 0.0,
) -> Tuple[HandoffVerdict, float, float, list]:
    """Apply the same thresholds to locally-derived probabilities.

    The heuristics stand in for Jev, so they are judged by the *same* rules. If
    a regex cannot see a problem and Jev is unreachable, the gate passes — and
    that residual blindness is why Level 1 exists to catch the cases a regex
    never will.
    """
    degradation, _ = _diff_signals(diff_summary)
    uncorroborated = _uncorroborated_claims(handoff_text, f"{test_output}\n{diff_summary}")

    reasons: list = []
    if degradation:
        p_degradation = max(p_degradation, 0.85)
        reasons.extend(degradation[:5])
    if uncorroborated:
        p_unverified = max(p_unverified, min(0.9, 0.45 + 0.15 * len(uncorroborated)))
        reasons.append(
            "claimed verification absent from the evidence: " + ", ".join(uncorroborated)
        )

    # Degradation is reported ahead of an unverified claim. A cheat is a
    # deliberate act and names a concrete remedy (restore the assertions), while
    # a missing artefact only says "supply the evidence". When a worker commits
    # both, the verdict and its message must lead with the one that tells the
    # worker what to actually change.
    if p_degradation > THRESHOLD_SILENT_DEGRADATION:
        return HandoffVerdict.SILENT_DEGRADATION, p_unverified, p_degradation, reasons
    if p_unverified > THRESHOLD_UNVERIFIED_CLAIM:
        return HandoffVerdict.UNVERIFIED_CLAIMS, p_unverified, p_degradation, reasons
    return HandoffVerdict.ACCEPTED, p_unverified, p_degradation, reasons


