def verify_handoff(
    handoff_text: str,
    test_exit_code: Optional[int],
    test_output: str = "",
    diff_summary: str = "",
    *,
    expected_files: Sequence[str] = (),
    key: Optional[str] = None,
    timeout: float = 8.0,
    api_url: Optional[str] = None,
    model: Optional[str] = None,
    use_jev: bool = False,
    allow_no_change: bool = False,
) -> HandoffReport:
    """Review a worker's Done declaration against its physical evidence.

    Level 1 settles everything a machine can measure and returns immediately on
    a failure. Level 2 asks Jev the two questions that genuinely need judgment,
    and falls back to heuristics when Jev cannot answer.

    ``use_jev`` defaults to **False**, so the deterministic heuristic is the
    baseline rather than the exception. This is the opposite of the obvious
    wiring and it is deliberate: see the "Jev calibration" note in the module
    docstring. Measured against ``jev-1.13.0``, an honest fully-corroborated
    handoff scored p=0.47-0.58 on a 0.35 block line, so a live model over-blocks
    correct work and a gate that refuses honest lanes is worse than no gate. A
    caller that wants the semantic layer opts in with ``use_jev=True`` and owns
    the threshold consequences. ``key`` still forces a specific path (an
    explicit empty string means "no key, heuristics only").
    """
    diff = parse_diff_summary(diff_summary)
    bounded_handoff = truncate_handoff(handoff_text or "")
    bounded_output = truncate_test_output(test_output or "")
    bounded_diff = truncate_diff(diff_summary or "")

    physical = _check_physical_facts(
        test_exit_code,
        diff,
        expected_files,
        allow_no_change=allow_no_change,
    )
    if physical is not None:
        return physical

    resolved_key = resolve_api_key(key) if use_jev else ""
    if not resolved_key:
        return _offline_report(
            bounded_handoff, bounded_output, bounded_diff, test_exit_code, diff
        )

    answers = _ask_jev(
        state={
            "captured_test_exit_code": test_exit_code,
            "worker_handoff_text": bounded_handoff,
            "test_output_snippet": bounded_output,
            "git_diff_summary": bounded_diff,
        },
        key=resolved_key,
        timeout=timeout,
        api_url=api_url,
        model=model,
    )
    if answers is None:
        return _offline_report(
            bounded_handoff, bounded_output, bounded_diff, test_exit_code, diff
        )

    p_unverified, p_degradation, actual_model = answers
    verdict, _, _, reasons = _heuristic_verdict(
        bounded_handoff, bounded_output, bounded_diff, p_unverified, p_degradation
    )
    return _finalize(
        verdict=verdict,
        p_unverified=p_unverified,
        p_degradation=p_degradation,
        model=actual_model,
        test_exit_code=test_exit_code,
        diff=diff,
        reasons=reasons,
    )


def _offline_report(
    handoff_text: str,
    test_output: str,
    diff_summary: str,
    test_exit_code: Optional[int],
    diff: DiffFacts,
) -> HandoffReport:
    verdict, p_unverified, p_degradation, reasons = _heuristic_verdict(
        handoff_text, test_output, diff_summary
    )
    return _finalize(
        verdict=verdict,
        p_unverified=p_unverified,
        p_degradation=p_degradation,
        model=HEURISTIC_MODEL,
        test_exit_code=test_exit_code,
        diff=diff,
        reasons=reasons,
    )


def _finalize(
    *,
    verdict: HandoffVerdict,
    p_unverified: float,
    p_degradation: float,
    model: str,
    test_exit_code: Optional[int],
    diff: DiffFacts,
    reasons: Sequence[str],
) -> HandoffReport:
    """Turn a verdict into a report, writing the message sent back to the worker."""
    specifics = f"Specifically: {'; '.join(reasons[:2])}. " if reasons else ""
    message = ""
    if verdict is HandoffVerdict.UNVERIFIED_CLAIMS:
        message = (
            f"Done rejected: the handoff contains unverified claims that the "
            f"evidence does not support (p={p_unverified:.2f} > "
            f"{THRESHOLD_UNVERIFIED_CLAIM}). {specifics}"
            "Supply the missing test evidence, or drop the claim. A summary you "
            "cannot prove will not be accepted."
        )
    elif verdict is HandoffVerdict.SILENT_DEGRADATION:
        message = (
            f"Done rejected: the diff shows the tests were weakened rather than "
            f"fixed (p={p_degradation:.2f} > {THRESHOLD_SILENT_DEGRADATION}). "
            f"{specifics}Commenting out assertions, deleting test cases, or adding "
            "skip markers to go green is forbidden. Restore the assertions and fix "
            "the code."
        )
    elif verdict is not HandoffVerdict.ACCEPTED:
        message = "Done rejected. See the physical evidence recorded above."

    return HandoffReport(
        verdict=verdict,
        accepted=verdict is HandoffVerdict.ACCEPTED,
        rejection_message=message,
        p_unverified_claim=p_unverified,
        p_silent_degradation=p_degradation,
        model=model,
        test_exit_code=test_exit_code,
        diff=diff,
        reasons=tuple(reasons),
    )
