def parse_diff_summary(diff_summary: str) -> DiffFacts:
    """Read change counts and paths out of a diff summary or a bare patch.

    Accepts every shape a caller is likely to have on hand:

    - ``git diff --stat`` — a ``path | n +++--`` block plus a totals line;
    - ``git diff --numstat`` — tab-separated counts;
    - ``git diff --name-only`` — bare paths;
    - a bare ``git diff`` unified patch — ``diff --git`` headers, ``@@`` hunks
      and ``+``/``-`` changed lines.

    The patch case is not a nicety. Plain ``git diff`` is the command a person
    types when asked for evidence of a change, and it is what CI logs and review
    comments already contain. A parser that only understood the ``--stat``
    family read that patch as *no change at all*, so :attr:`DiffFacts.has_changes`
    was False and the review refused the lane for "no diff" — while a worker who
    had deleted the very assertion the gate exists to protect sailed past the
    degradation check entirely. A blind spot in the evidence reader is a
    disabled gate, so the patch is parsed on the same footing as the summaries.

    Parsing stays forgiving on purpose: input this function cannot fully
    understand is still evidence that files were touched, never evidence that
    nothing was.
    """
    if not diff_summary:
        return DiffFacts()

    files: list[str] = []
    files_changed = insertions = deletions = 0
    totals_seen = False
    # The path of the file the current unified-diff section belongs to, so a
    # headerless paste can still attribute its +/- lines to a file.
    patch_path = ""

    for raw_line in diff_summary.splitlines():
        line = raw_line.rstrip()
        if not line.strip():
            continue

        totals = _TOTALS_RE.search(line)
        if totals:
            files_changed = int(totals.group(1))
            insertions = int(totals.group(2) or 0)
            deletions = int(totals.group(3) or 0)
            totals_seen = True
            continue

        numstat = _NUMSTAT_RE.match(line)
        if numstat:
            added, removed, path = numstat.groups()
            if added != "-":
                insertions += int(added)
            if removed != "-":
                deletions += int(removed)
            path = path.strip()
            if path and path not in files:
                files.append(path)
            continue

        # --- unified patch ---
        # Handled before the stat branch: a `--- a/x` line contains a pipe-free
        # path that the bare-path branch would otherwise mistake for a
        # --name-only entry.
        header = _DIFF_HEADER_RE.match(line)
        if header:
            # A rename or copy lists two paths; the destination is the file in
            # its new location, which is the one now being edited.
            patch_path = header.group("dst").strip()
            if patch_path and patch_path != _DEV_NULL and patch_path not in files:
                files.append(patch_path)
            continue

        hunk = _HUNK_RE.match(line)
        if hunk:
            continue

        old_file = _OLD_FILE_RE.match(line)
        if old_file:
            candidate = old_file.group("path").strip()
            patch_path = "" if candidate == _DEV_NULL else candidate
            continue

        new_file = _NEW_FILE_RE.match(line)
        if new_file:
            candidate = new_file.group("path").strip()
            if candidate and candidate != _DEV_NULL:
                patch_path = candidate
                if candidate not in files:
                    files.append(candidate)
            continue

        if line[0] in "+-":
            # A changed line. Counted so `has_changes` is true even for a patch
            # whose only change is a blank line, and so a scope expectation can
            # be checked against a patch that carried no totals line.
            if line[0] == "+":
                insertions += 1
            else:
                deletions += 1
            # A headerless patch still attributes to whatever file the last
            # `--- a/x` / `+++ b/x` pair named.
            if patch_path and patch_path not in files:
                files.append(patch_path)
            continue

        stat = _STAT_LINE_RE.match(line)
        if stat:
            path = stat.group(1).strip()
            if path and path not in files:
                files.append(path)
            continue

        if line.strip() in _NOISE_TOKENS:
            continue

        # A bare path line, as produced by --name-only.
        if line == line.strip() and " " not in line.strip():
            path = line.strip()
            if path not in files:
                files.append(path)

    if not totals_seen and files:
        # No totals line, so derive the file count from the paths we did see.
        files_changed = max(files_changed, len(files))

    return DiffFacts(
        files_changed=files_changed,
        insertions=insertions,
        deletions=deletions,
        files=tuple(files),
    )


def evidence_present(
    test_exit_code: Optional[int],
    test_output: str = "",
    diff: Optional[DiffFacts] = None,
) -> bool:
    """Whether the physical facts needed to even ask a question are present."""
    if test_exit_code is None or test_exit_code != 0:
        return False
    facts = diff if diff is not None else parse_diff_summary(test_output)
    return facts.has_changes


def _check_physical_facts(
    test_exit_code: Optional[int],
    diff: DiffFacts,
    expected_files: Sequence[str],
    *,
    allow_no_change: bool = False,
) -> Optional[HandoffReport]:
    """Decide the Level 1 questions, or return ``None`` to proceed to Jev.

    Every branch here is a fact a machine can measure, so every branch blocks
    without a model call. ``expected_files`` is optional; when the caller
    supplies it, a diff that touches none of them means the handoff's stated
    scope and the real scope disagree, which is a fact, not a judgment.
    """
    if test_exit_code is None:
        return HandoffReport(
            verdict=HandoffVerdict.PHYSICAL_EVIDENCE_MISSING,
            accepted=False,
            rejection_message=(
                "Done rejected: no test exit code was captured. A Done claim "
                "without a physical test result is unproven, and an unproven "
                "claim does not pass. Re-run the suite and report its exit code."
            ),
            diff=diff,
            reasons=("no test exit code supplied",),
        )

    if test_exit_code != 0:
        return HandoffReport(
            verdict=HandoffVerdict.PHYSICAL_TEST_FAILED,
            accepted=False,
            rejection_message=(
                f"Done rejected: tests failed with exit code {test_exit_code}. "
                "A red suite is a fact and blocks here; no further review is needed."
            ),
            test_exit_code=test_exit_code,
            diff=diff,
            reasons=(f"test suite exit code {test_exit_code} is non-zero",),
        )

    if allow_no_change:
        if diff.has_changes:
            return HandoffReport(
                verdict=HandoffVerdict.PHYSICAL_DIFF_MISMATCH,
                accepted=False,
                rejection_message=(
                    "No-change rejected: the git diff summary contains changes. "
                    "A no-change result must prove that nothing was modified."
                ),
                test_exit_code=test_exit_code,
                diff=diff,
                reasons=("no-change outcome contradicts the diff summary",),
            )
    elif not diff.has_changes:
        return HandoffReport(
            verdict=HandoffVerdict.PHYSICAL_DIFF_MISSING,
            accepted=False,
            rejection_message=(
                "Done rejected: the git diff summary shows no changes. "
                "Completion was claimed but no code was touched."
            ),
            test_exit_code=test_exit_code,
            diff=diff,
            reasons=("diff summary contains no insertions, deletions or files",),
        )

    wanted = [f for f in (expected_files or []) if f]
    if wanted:
        touched = tuple(f for f in wanted if _touches(diff, f))
        if not touched:
            return HandoffReport(
                verdict=HandoffVerdict.PHYSICAL_DIFF_MISMATCH,
                accepted=False,
                rejection_message=(
                    "Done rejected: the diff touches none of the files the handoff "
                    f"claims to have changed ({', '.join(wanted)}). "
                    f"Actual changes: {', '.join(diff.files) or 'none reported'}."
                ),
                test_exit_code=test_exit_code,
                diff=diff,
                reasons=("claimed scope and real scope disagree",),
            )

    return None


def _touches(diff: DiffFacts, wanted: str) -> bool:
    """Whether ``diff`` modified ``wanted``.

    Matches on a full path or on a path suffix, so an expectation of
    ``handoff_judge.py`` is satisfied by ``lib/handoff_judge.py``.
    """
    target = wanted.strip().lstrip("./")
    for path in diff.files:
        candidate = path.strip().lstrip("./")
        if candidate == target or candidate.endswith("/" + target):
            return True
    return False


