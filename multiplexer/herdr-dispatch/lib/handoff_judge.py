"""Gate C: Handoff Truthfulness Reviewer (Issue #132).

The failure this exists to prevent
----------------------------------
**Fake Completion**: a worker writes a confident handoff — "Fixed the leak,
verified with valgrind, zero leaks" — while the only thing that actually
happened was one line edited, a test deleted, or nothing at all. Orchestrators
that read prose as evidence are structurally unable to catch this, because the
prose is generated by the same process that could have taken the shortcut.

Canny's rule, and why the split matters
---------------------------------------
*"Facts go to code. Judgments go to Jev. Only facts can block."*

So this module refuses to spend a model call on anything a machine can settle:

- **Level 1 (code, no Jev).** A non-zero test exit code, an absent exit code, a
  diff with no changes, or a diff that never touches the files the handoff
  claims to have changed: each is a fact, and each blocks in code. Asking Jev
  whether a red suite is red burns tokens to learn something ``int()`` already
  knows, and lets a confident model talk the gate out of a fact.
- **Level 2 (Jev Noul).** Only the genuinely semantic questions are delegated:
  does the handoff assert things absent from the evidence (``unverified_claim``),
  and did the diff buy green by weakening the tests
  (``silent_degradation``). Probabilities over 0.35 and 0.20 respectively block
  the Done declaration and produce a message the orchestrator can hand straight
  back to the worker.

Deliberate non-goals (Occam)
----------------------------
This module never runs the tests, never shells out to ``git``, and never sends
a reject message to a worker. Facts arrive as arguments; the verdict leaves as a
dataclass. A reviewer that also manufactured its own evidence would not be a
reviewer. :mod:`closeout_gate` consumes the verdict, and ``dispatch_plugin.py``
wires it to the command line.

Context discipline
------------------
Jev is fed a *bounded* view: at most :data:`MAX_HANDOFF_CHARS` of the handoff,
the last :data:`MAX_TEST_OUTPUT_CHARS` of the log, and
:data:`MAX_DIFF_SUMMARY_CHARS` of the diff. A full transcript is both expensive
and actively harmful — it invites the model to reason about a worker's narration
instead of the evidence. The offline heuristic is held to the same bound, so the
gate never knows more than Jev does.

Resilience: when no key is configured, or the network fails, or the endpoint
returns something that is not JSON, the built-in heuristics decide. Degradation
is the one finding a regex can make well, because commenting out an assertion
leaves a literal ``+`` line in a diff.

Known limitation: Jev calibration
---------------------------------
The semantic thresholds below are Issue #132's, and they are only as good as the
probabilities behind them. Measured against ``jev-1.13.0`` on 2026-10-01, an
honest, fully-corroborated handoff scored **p=0.47-0.58** on
``unverified_claim_detected`` — above the 0.35 block threshold — when the
question was phrased as an accusation ("does the handoff claim things absent
from the evidence?"). Re-framing the same question as an agreement ("is every
claim corroborated?") moved the same handoff to 0.13, but then inverted the
answer on a cheating handoff, so the correction was not reliable either.

The practical consequence: with a live key, expect the Jev layer to over-block
honest work, and prefer ``--offline`` (or an unset ``TYPESAFE_API_KEY``) when
you want a deterministic verdict. The heuristics do not have this problem —
they accept a corroborated delivery and reject a weakened one. The measurements
are reported on Issue #132 for re-tuning; the thresholds are deliberately left
as specified rather than silently retuned from one lane's evidence.
"""

from __future__ import annotations

import json
import os
import re
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Dict, Mapping, Optional, Sequence, Tuple

DEFAULT_TYPESAFE_API_URL = "https://api.typesafe.ai/v1/systemone"
DEFAULT_JEV_MODEL = "jev-latest"

# Context bounds. Generous enough to keep the evidence that matters, small
# enough that a full worker transcript can never be shipped to the model.
MAX_HANDOFF_CHARS = 4000
MAX_TEST_OUTPUT_CHARS = 1500
MAX_DIFF_SUMMARY_CHARS = 2000

# Thresholds from Issue #132. Unverified claims block at 0.35; silent
# degradation blocks lower, at 0.20, because weakening an assertion is a
# deliberate act rather than a careless one and should not need much evidence.
THRESHOLD_UNVERIFIED_CLAIM = 0.35
THRESHOLD_SILENT_DEGRADATION = 0.20

TRUNCATION_MARKER = "\n... [truncated] ...\n"
HEURISTIC_MODEL = "heuristic-fallback"

# --- diff parsing -----------------------------------------------------------

_NUMSTAT_RE = re.compile(r"^(\d+|-)\t(\d+|-)\t(.+)$")
_STAT_LINE_RE = re.compile(r"^\s*(\S.*?)\s*\|\s*(?:\d+|Bin)\b.*$")
_TOTALS_RE = re.compile(
    r"(\d+)\s+files?\s+changed"
    r"(?:,\s*(\d+)\s+insertions?\(\+\))?"
    r"(?:,\s*(\d+)\s+deletions?\(-\))?",
    re.IGNORECASE,
)
_NOISE_TOKENS = frozenset({"...", "---", "+++"})

# A bare `git diff` patch. The three summary shapes above (``--stat``,
# ``--numstat``, ``--name-only``) are all *summaries*; a caller who runs plain
# ``git diff`` — the obvious thing to do, and what most CI logs already contain —
# gets a unified patch, which none of them match. Every line then falls through
# to the bare-path branch and is discarded, so the diff reads as empty and a
# deleted assertion is never seen.
_DIFF_HEADER_RE = re.compile(r"^diff --git\s+a/(?P<src>.+?)\s+b/(?P<dst>.+?)\s*$")
# `--- a/path` / `+++ b/path` carry the real path when a header is absent (a
# patch pasted without its `diff --git` preamble, which is what a chat paste or
# a truncated log tends to be).
_OLD_FILE_RE = re.compile(r"^--- (?:a/)?(?P<path>\S.*?)\s*$")
_NEW_FILE_RE = re.compile(r"^\+\+\+ (?:b/)?(?P<path>\S.*?)\s*$")
# `@@ -1,4 +1,3 @@` — a hunk header proves the patch has content even when every
# changed line happens to be blank.
_HUNK_RE = re.compile(r"^@@+ .*? @@")
# `/dev/null` means the file was added or deleted outright, so it names nothing.
_DEV_NULL = "/dev/null"

# --- degradation heuristics -------------------------------------------------
# Every pattern anchors on a diff marker at column 0. That is what separates a
# changed line from a `--stat` header (` lib/parser.py | 14 ++++---`) or a
# totals line (` 2 files changed, 29 insertions(+)`), both of which contain
# plus and minus characters but sit one column to the right.

_ASSERTION_BODY = (
    r"(?:assert\b|assert[A-Z]\w*\(|\w*assert\w*\s*\(|"
    r"(?:verify|expect|should|check)\s*\()"
)
_REMOVED_ASSERTION_RE = re.compile(r"^-\s*" + _ASSERTION_BODY)
_COMMENTED_ASSERTION_RE = re.compile(r"^\+\s*(?:#|//|\*)\s*" + _ASSERTION_BODY)
_SKIPPED_TEST_RE = re.compile(
    r"^\+.*(?:"
    r"@pytest\.mark\.(?:skip|skipif|xfail)\b"
    r"|@unittest\.?(?:skip|expectedFailure)\b"
    r"|@ignore\b"
    r"|\b(?:xit|xdescribe)\s*\("
    r"|\b(?:it|test|describe)\.skip\s*\("
    r"|\bdescribe\.only\s*\("
    r"|\bt\.Skip\s*\("
    r"|\bskipTest\s*\("
    r")",
    re.IGNORECASE,
)
_REMOVED_VALIDATION_RE = re.compile(r"^-\s*(?:raise\b|throw\b|if\s+not\b.*\braise\b)")

# --- unverified-claim heuristic ---------------------------------------------
# Only exotic verification tools are listed. A plain "ran the tests" claim is
# already corroborated by a passing log, and listing it would make every
# ordinary handoff look unverified. Each entry is a regex searched for in the
# handoff, then again in the evidence.
_VERIFICATION_TOOL_PATTERNS: Dict[str, str] = {
    "valgrind": r"\bvalgrind\b",
    "sanitizer": r"\b(?:asan|tsan|msan|ubsan|address sanitizer|leak sanitizer)\b",
    "mypy": r"\bmypy\b",
    "ruff": r"\bruff\b",
    "eslint": r"\beslint\b",
    "typecheck": r"\b(?:tsc|typecheck|type-check)\b",
    "benchmark": r"\bbench(?:mark)?(?:ing|s)?\b",
    "browser/e2e suite": r"\b(?:e2e|playwright|cypress|selenium|puppeteer)\b",
    "load test": r"\b(?:load test(?:ing)?|locust|\bk6\b|jmeter|vegeta)\b",
    "mutation test": r"\b(?:mutation test(?:ing)?|mutmut|cosmic.?ray)\b",
    "fuzzing": r"\b(?:fuzz(?:ing)?|atheris)\b",
    "pre-commit": r"\bpre-commit\b",
}

# A tool only counts as "claimed" when the handoff attaches it to a
# verification claim. "Added regression coverage for the parser" must not become
# a coverage-tool claim; "verified with valgrind" must.
_VERIFICATION_CONTEXT_RE = re.compile(
    r"(?:\b(?:verif\w+|validat\w+|confirm\w+|check\w+|proof|proved|test\w*|run|ran|"
    r"pass\w*|execut\w+|us\w+|under|with|via|using)\b|[:：])"
    r"[^\n]{0,60}",
    re.IGNORECASE,
)


class HandoffVerdict(str, Enum):
    """Why a Done declaration was accepted or refused."""

    ACCEPTED = "ACCEPTED"
    PHYSICAL_TEST_FAILED = "PHYSICAL_TEST_FAILED"
    PHYSICAL_EVIDENCE_MISSING = "PHYSICAL_EVIDENCE_MISSING"
    PHYSICAL_DIFF_MISSING = "PHYSICAL_DIFF_MISSING"
    PHYSICAL_DIFF_MISMATCH = "PHYSICAL_DIFF_MISMATCH"
    UNVERIFIED_CLAIMS = "UNVERIFIED_CLAIMS"
    SILENT_DEGRADATION = "SILENT_DEGRADATION"


@dataclass(frozen=True)
class DiffFacts:
    """Physical facts read out of a diff summary.

    ``files_changed`` falls back to the number of distinct paths when the
    summary carries no totals line, so a bare ``--name-only`` listing is still
    evidence that work happened.
    """

    files_changed: int = 0
    insertions: int = 0
    deletions: int = 0
    files: Tuple[str, ...] = ()

    @property
    def has_changes(self) -> bool:
        """Whether the diff shows any change at all.

        A file listed with zero line changes still counts: a rename or a mode
        change is a real, inspectable modification. Only a completely empty or
        explicitly zero diff is treated as "no work happened".
        """
        return bool(self.files) or self.insertions > 0 or self.deletions > 0 or self.files_changed > 0


@dataclass(frozen=True)
class HandoffReport:
    """The verdict plus the evidence behind it."""

    verdict: HandoffVerdict
    accepted: bool
    rejection_message: str = ""
    p_unverified_claim: float = 0.0
    p_silent_degradation: float = 0.0
    model: str = HEURISTIC_MODEL
    test_exit_code: Optional[int] = None
    diff: DiffFacts = field(default_factory=DiffFacts)
    reasons: Tuple[str, ...] = ()

    def as_truthfulness_facts(self) -> Dict[str, Any]:
        """The fact bundle :mod:`closeout_gate` consumes.

        ``verified`` is deliberately redundant with ``accepted``: the gate
        requires a caller to say it verified the work, not merely that a verdict
        string looked positive.
        """
        return {
            "handoff_verdict": self.verdict.value,
            "handoff_accepted": self.accepted,
            "verified": self.accepted,
        }

    def as_dict(self) -> Dict[str, Any]:
        return {
            "verdict": self.verdict.value,
            "accepted": self.accepted,
            "rejection_message": self.rejection_message,
            "p_unverified_claim": round(self.p_unverified_claim, 4),
            "p_silent_degradation": round(self.p_silent_degradation, 4),
            "model": self.model,
            "physical": {
                "test_exit_code": self.test_exit_code,
                "files_changed": self.diff.files_changed,
                "insertions": self.diff.insertions,
                "deletions": self.diff.deletions,
            },
            "reasons": list(self.reasons),
        }

    def render(self) -> str:
        lines = [f"handoff truth gate: {self.verdict.value}"]
        lines.append(
            "  physical: "
            f"exit_code={self.test_exit_code} "
            f"files={self.diff.files_changed} "
            f"+{self.diff.insertions}/-{self.diff.deletions}"
        )
        lines.append(
            f"  semantic: p_unverified_claim={self.p_unverified_claim:.2f} "
            f"p_silent_degradation={self.p_silent_degradation:.2f} [{self.model}]"
        )
        for reason in self.reasons:
            lines.append(f"  - {reason}")
        if self.accepted:
            lines.append("  ACCEPTED: the Done declaration is corroborated by evidence")
        else:
            lines.append(f"  REJECTED: {self.rejection_message}")
        return "\n".join(lines)


